#!/bin/bash

set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" &>/dev/null && pwd)

# shellcheck source=../common/log.sh
source "$SCRIPT_DIR/../common/log.sh"
# shellcheck source=../common/symlink.sh
source "$SCRIPT_DIR/../common/symlink.sh"

# Source .dotconfig if variables aren't already set
DOTCONFIG="$SCRIPT_DIR/../../.dotconfig"
if [[ -z "${DOT_NAME:-}" || -z "${DOT_EMAIL:-}" ]] && [[ -f "$DOTCONFIG" ]]; then
	# shellcheck source=../../.dotconfig
	source "$DOTCONFIG"
	debug "Loaded configuration from .dotconfig"
fi

DOT_NAME=${DOT_NAME:-}
DOT_EMAIL=${DOT_EMAIL:-}
DOT_SIGNING_KEY=${DOT_SIGNING_KEY:-${DOT_YUBIKEY:-}} # DOT_YUBIKEY = old name

if [ ! -d "$HOME/dev" ]; then
	mkdir "$HOME/dev"

	info "Created ~/dev folder"
fi

if [ ! -d "$HOME/projects" ]; then
	mkdir "$HOME/projects"

	info "Created ~/projects folder"
fi

GITCONFIG_TEMPLATE="$SCRIPT_DIR/../../configs/git/.gitconfig.template"
GITCONFIG_TARGET="$HOME/.gitconfig"

if [[ -f "$GITCONFIG_TEMPLATE" ]]; then
	# Always overwrite existing config to ensure updates
	debug "Generating .gitconfig with current user values..."

	# Debug: Show what variables we have
	debug "Debug: DOT_NAME='${DOT_NAME:-NOT_SET}'"
	debug "Debug: DOT_EMAIL='${DOT_EMAIL:-NOT_SET}'"
	debug "Debug: DOT_SIGNING_KEY='${DOT_SIGNING_KEY:-NOT_SET}'"

	# Configure sed for macOS (BSD) vs GNU differences
	if sed --version >/dev/null 2>&1; then
		SED_INLINE=(sed -i)
	else
		SED_INLINE=(sed -i '')
	fi

	# A ~/.gitconfig this script did not write (a machine set up by hand, a fresh
	# Windows box) is moved aside, never deleted. Ours carries the marker line, so
	# a rerun regenerates in place without piling up backups.
	GITCONFIG_MARKER="# Generated by dotfiles script/git/setup.sh from configs/git/.gitconfig.template"
	if [[ -L "$GITCONFIG_TARGET" ]]; then
		rm -f "$GITCONFIG_TARGET" # an old symlink into the repo; nothing of its own to keep
	elif [[ -e "$GITCONFIG_TARGET" ]] && ! grep -qF "$GITCONFIG_MARKER" "$GITCONFIG_TARGET"; then
		GITCONFIG_BACKUP="${GITCONFIG_TARGET}_$(date +%Y%m%d-%H%M%S).bak"
		mv "$GITCONFIG_TARGET" "$GITCONFIG_BACKUP"
		info "Existing ~/.gitconfig kept as $GITCONFIG_BACKUP"
	fi
	{
		echo "$GITCONFIG_MARKER"
		cat "$GITCONFIG_TEMPLATE"
	} >"$GITCONFIG_TARGET"

	# The values go into a sed replacement: escape what sed would interpret there.
	sed_escape() { printf '%s' "$1" | sed 's/[&|\\]/\\&/g'; }
	DOT_NAME_SED=$(sed_escape "${DOT_NAME:-}")
	DOT_EMAIL_SED=$(sed_escape "${DOT_EMAIL:-}")
	DOT_SIGNING_KEY_SED=$(sed_escape "${DOT_SIGNING_KEY:-}")

	# Replace placeholders with actual values using proper sed escaping
	if [[ -n "${DOT_NAME:-}" ]]; then
		"${SED_INLINE[@]}" "s|__DOT_NAME__|${DOT_NAME_SED}|g" "$GITCONFIG_TARGET"
		debug "Replaced __DOT_NAME__ with: $DOT_NAME"
	fi

	if [[ -n "${DOT_EMAIL:-}" ]]; then
		"${SED_INLINE[@]}" "s|__DOT_EMAIL__|${DOT_EMAIL_SED}|g" "$GITCONFIG_TARGET"
		debug "Replaced __DOT_EMAIL__ with: $DOT_EMAIL"
	fi

	if [[ -n "${DOT_SIGNING_KEY:-}" ]]; then
		"${SED_INLINE[@]}" "s|__DOT_SIGNING_KEY__|${DOT_SIGNING_KEY_SED}|g" "$GITCONFIG_TARGET"
		success "Applied SSH signing key (signed via 1Password)"
	else
		# Remove signing key + gpgsign sections if no signing key provided
		"${SED_INLINE[@]}" '/signingkey = __DOT_SIGNING_KEY__/d' "$GITCONFIG_TARGET"
		"${SED_INLINE[@]}" '/^\[commit\]$/,/^$/d;/^\[tag\]$/,/^$/d;/^\[gpg\]$/,/^$/d' "$GITCONFIG_TARGET"
		info "No signing key provided - removed signing configuration"
	fi

	# op-ssh-sign lives inside the macOS app bundle; elsewhere fall back to
	# ssh-keygen (Linux builds have FIDO support compiled in).
	if [[ "$(uname)" != "Darwin" ]]; then
		"${SED_INLINE[@]}" 's|program = /Applications/1Password.app/Contents/MacOS/op-ssh-sign|program = ssh-keygen|' "$GITCONFIG_TARGET"
	fi

	# The template names nvim and bat. Each profile's apps/* module runs before this
	# one, so what is on PATH now is what the machine will have: the server profile
	# has no bat (Debian's package installs it as batcat), Windows has neither.
	# A pager that does not exist makes every `git log`/`git diff` print nothing.
	if ! command -v nvim >/dev/null 2>&1; then
		for GIT_EDITOR_FALLBACK in vim vi; do
			if command -v "$GIT_EDITOR_FALLBACK" >/dev/null 2>&1; then
				"${SED_INLINE[@]}" "s|editor = nvim\$|editor = ${GIT_EDITOR_FALLBACK}|" "$GITCONFIG_TARGET"
				info "nvim not found - git editor set to $GIT_EDITOR_FALLBACK"
				break
			fi
		done
	fi
	if ! command -v bat >/dev/null 2>&1; then
		if command -v batcat >/dev/null 2>&1; then
			"${SED_INLINE[@]}" 's|pager = bat$|pager = batcat|' "$GITCONFIG_TARGET"
			info "bat is installed as batcat - git pager set to batcat"
		else
			"${SED_INLINE[@]}" '/^[[:space:]]*pager = bat$/d' "$GITCONFIG_TARGET"
			info "bat not found - git pager left at its default"
		fi
	fi

	DOT_DISPLAY_NAME=${DOT_NAME:-Unknown}
	DOT_DISPLAY_EMAIL=${DOT_EMAIL:-unknown@example.com}
	success "Updated .gitconfig with: ${DOT_DISPLAY_NAME} <${DOT_DISPLAY_EMAIL}>"
else
	error "Git config template not found at $GITCONFIG_TEMPLATE"
fi

# Removed conflicting symlink - using template generation above instead
link_file "$SCRIPT_DIR/../../configs/git/.gitignore_global" "$HOME/.gitignore_global"
link_file "$SCRIPT_DIR/../../configs/git/work.gitconfig" "$HOME/projects/.gitconfig"

# Configure git if DOT_NAME and DOT_EMAIL are provided
if [[ -n "$DOT_NAME" && -n "$DOT_EMAIL" ]]; then
	debug "Configuring git with provided credentials..."
	git config --global user.name "$DOT_NAME"
	git config --global user.email "$DOT_EMAIL"
	success "Git configured: $DOT_NAME <$DOT_EMAIL>"
fi
